"""Speedrun baseline: train a small action-conditioned frame predictor until the FLOP budget is used,
then report the 12-frame rollout MSE on the fixed validation rollouts.

    python3 train.py                  # from speedrun/tracks/world-model-tiny/
    python3 train.py --budget 1e13    # shorter run, not a record

Model: a small conv U-Net. Input: the last 4 frames (12 channels). The action enters at the 8 x 8 bottleneck
(FiLM: a learned scale and shift per channel). Output: the last frame plus a learned change, so at the start it
copies the last frame. Training is one step ahead with true frames as input (teacher forcing); evaluation rolls
the model forward 12 steps on its own predictions. Adam, constant learning rate, then a linear cooldown.
Training rollouts are new every step, generated by env.py from seeds 0, 1, 2, ... (never eval.VAL_SEED).
"""
import argparse
import json
import os
import sys
import time

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

TRACK = os.path.dirname(os.path.abspath(__file__))
while not os.path.exists(os.path.join(TRACK, "eval.py")):  # a copy in records/<run>/ finds the track folder
    TRACK = os.path.dirname(TRACK)
sys.path[:0] = [TRACK, os.path.join(os.path.dirname(os.path.dirname(TRACK)), "common")]  # env, eval, flops
import env  # noqa: E402
import eval as ev  # noqa: E402
import flops  # noqa: E402

BUDGET = 1e14  # the speedrun budget, in FLOPs (README.md)
C1, C2 = 32, 64  # channels at 32 x 32 and at 16 x 16 / 8 x 8
N_RES = 2  # residual blocks at the 8 x 8 bottleneck
ROLLOUTS = 16  # rollouts per step; each gives 12 one-step examples, so the batch is 192 frames
LR, COOLDOWN = 2e-3, 0.4  # learning rate falls linearly to 0 over the last 40% of steps
MEM_GB = 1.5  # cap on GPU memory for this process


class Res(nn.Module):
    def __init__(self, c):
        super().__init__()
        self.n1, self.n2 = nn.GroupNorm(8, c), nn.GroupNorm(8, c)
        self.c1, self.c2 = nn.Conv2d(c, c, 3, padding=1), nn.Conv2d(c, c, 3, padding=1)
        self.film = nn.Embedding(env.N_ACTIONS, 2 * c)
        nn.init.zeros_(self.film.weight)

    def forward(self, x, a):
        scale, shift = self.film(a)[:, :, None, None].chunk(2, 1)
        h = self.c1(F.silu(self.n1(x)))
        h = self.n2(h) * (1 + scale) + shift
        return x + self.c2(F.silu(h))


class Predictor(nn.Module):
    def __init__(self):
        super().__init__()
        self.inp = nn.Conv2d(3 * ev.CONTEXT, C1, 3, padding=1)
        self.down1 = nn.Conv2d(C1, C2, 4, stride=2, padding=1)  # 32 -> 16
        self.down2 = nn.Conv2d(C2, C2, 4, stride=2, padding=1)  # 16 -> 8
        self.mid = nn.ModuleList(Res(C2) for _ in range(N_RES))
        self.up2 = nn.ConvTranspose2d(C2, C2, 4, stride=2, padding=1)  # 8 -> 16
        self.up1 = nn.ConvTranspose2d(C2, C1, 4, stride=2, padding=1)  # 16 -> 32
        self.out = nn.Conv2d(C1, 3, 3, padding=1)
        nn.init.zeros_(self.out.weight)
        nn.init.zeros_(self.out.bias)

    def forward(self, frames, a):  # frames (B, 4, 3, 32, 32), a (B,) -> next frame (B, 3, 32, 32)
        h1 = F.silu(self.inp(frames.flatten(1, 2)))
        h2 = F.silu(self.down1(h1))
        h = F.silu(self.down2(h2))
        for r in self.mid:
            h = r(h, a)
        h = F.silu(self.up2(h) + h2)
        h = F.silu(self.up1(h) + h1)
        return frames[:, -1] + self.out(h)


def build():
    model = Predictor()
    return model, [torch.optim.Adam(model.parameters(), lr=LR, betas=(0.9, 0.99))]


def windows(frames, actions):
    """(R, 16, 3, 32, 32), (R, 15) -> 12 one-step examples per rollout: 4 true frames, action, next frame."""
    idx = torch.arange(ev.CONTEXT, ev.CONTEXT + ev.HORIZON)
    x = torch.stack([frames[:, t - ev.CONTEXT:t] for t in idx], 1).flatten(0, 1)
    a = actions[:, idx - 1].flatten()
    y = frames[:, idx].flatten(0, 1)
    return x, a, y


def train_step(model, opts, x, a, y):
    loss = F.mse_loss(model(x, a), y)
    loss.backward()
    for o in opts:
        o.step()
    model.zero_grad(set_to_none=True)
    return loss.detach()


def make_inputs():
    n = ROLLOUTS * ev.HORIZON
    return (torch.zeros(n, ev.CONTEXT, 3, env.SIZE, env.SIZE), torch.zeros(n, dtype=torch.long),
            torch.zeros(n, 3, env.SIZE, env.SIZE))


def predict_fn(model):
    def predict(ctx, actions):  # roll the model forward on its own predictions
        frames, out = list(ctx.unbind(1)), []
        for k in range(ev.HORIZON):
            t = ev.CONTEXT - 1 + k  # last known frame; actions[:, t] leads to frame t + 1
            nxt = model(torch.stack(frames[-ev.CONTEXT:], 1), actions[:, t]).clamp(0, 1)
            frames.append(nxt)
            out.append(nxt)
        return torch.stack(out, 1)
    return predict


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--budget", type=float, default=BUDGET)
    args = ap.parse_args()
    device = "cuda" if torch.cuda.is_available() else "mps" if torch.backends.mps.is_available() else "cpu"
    if device == "mps":
        torch.mps.set_per_process_memory_fraction(min(1.0, MEM_GB * 1e9 / torch.mps.recommended_max_memory()))
    torch.manual_seed(0)
    model, opts = build()  # built on cpu so the starting weights are the same on every machine
    model.to(device)
    for o in opts:
        for g in o.param_groups:
            g["base_lr"] = g["lr"]
    n_params = sum(p.numel() for p in model.parameters())
    print(f"device {device}, params {n_params:,}, budget {args.budget:.3g} FLOPs")

    step_flops = flops.count_step_inputs(build, train_step, make_inputs)
    n_steps = int(args.budget // step_flops)
    print(f"FLOPs per step {step_flops:.4g} (FlopCounterMode), steps {n_steps}, "
          f"rollouts {n_steps * ROLLOUTS:,}, frames predicted {n_steps * ROLLOUTS * ev.HORIZON:,}")

    t0 = time.time()
    for i in range(n_steps):
        scale = min(1.0, (1 - i / n_steps) / COOLDOWN)
        for o in opts:
            for g in o.param_groups:
                g["lr"] = g["base_lr"] * scale
        assert i != ev.VAL_SEED
        f, a = env.generate(ROLLOUTS, seed=i, t=ev.CONTEXT + ev.HORIZON)
        f = torch.from_numpy(f).to(device).float() / 255
        x, a, y = windows(f, torch.from_numpy(a).to(device))
        loss = train_step(model, opts, x, a, y)
        if i % 500 == 0 or i == n_steps - 1:
            print(f"step {i}/{n_steps} loss {loss.item():.6f} flops {(i + 1) * step_flops:.4g} "
                  f"time {time.time() - t0:.0f}s", flush=True)
    if device == "mps":
        torch.mps.synchronize()
    train_time = time.time() - t0

    model.eval()
    t1 = time.time()
    score = ev.rollout_mse(predict_fn(model), device)
    peak = torch.mps.driver_allocated_memory() if device == "mps" else 0
    result = dict(val_mse=float(f"{score:.4g}"), flops=float(f"{n_steps * step_flops:.6g}"), budget=args.budget,
                  steps=n_steps, rollouts=n_steps * ROLLOUTS, params=n_params, device=device,
                  train_seconds=round(train_time, 1), eval_seconds=round(time.time() - t1, 1),
                  mps_driver_mb=round(peak / 1e6))
    print("result " + json.dumps(result))


if __name__ == "__main__":
    main()
